// 标题生成：基于鲁肃设计的"7 种爆款公式 + 主公调性词"
// 笔记生成：基于鲁肃设计的"5 段式结构 + 450-550 字控制"
// ================================================

/**
 * 主公调性词（鲁肃设计 v1 · 2026-06-04）
 * 这些是主公亲自盯过的"调性"——口语、亲切、敢说真话、不端架子
 */
const TONE_KEYWORDS = [
  '说人话',
  '别端着',
  '不卖课',
  '真用过',
  '敢拍胸脯',
  '不绕弯子',
  '看完就能用',
];

/**
 * 7 种爆款标题公式（鲁肃设计 v1）
 * 每条公式对应一个编号 + 模板
 */
const TITLE_FORMULAS = [
  { id: 1, name: '数字清单型',   template: '【{topic}】亲测 {n} 个小窍门，第 {k} 个真的香 {emoji}' },
  { id: 2, name: '小白入门型',   template: '{topic}小白也能上手｜一文讲透不踩雷' },
  { id: 3, name: '反常识避雷型', template: '别再乱买{topic}了！这篇看完省 2000' },
  { id: 4, name: '保姆攻略型',   template: '{topic}必看｜从 0 到 1 的保姆级攻略' },
  { id: 5, name: '真实体验型',   template: '我为什么把{topic}扔了 80%？真实体验分享' },
  { id: 6, name: '对比测评型',   template: '{topic}横评 5 款｜这款真的别再买了' },
  { id: 7, name: '痛点共鸣型',   template: '{topic}踩坑 3 年才懂｜这 1 件事越早做越好' },
];

const SUGGESTED_EMOJIS = ['🍃', '✨', '🔥', '💡', '🛒', '📌', '🌟', '💰', '🎯', '❤️'];

/**
 * 标题生成 Prompt
 * 策略：让模型直接产出 5 条 JSON 数组，每条带标题 + 公式编号 + 钩子句 + emoji
 */
function buildTitlePrompt(topic) {
  const formulaList = TITLE_FORMULAS
    .map(f => `${f.id}. ${f.name}：${f.template}`)
    .join('\n');

  return `你是小红书爆款标题专家。用户输入主题："${topic}"，请你从以下 7 种公式中**至少使用 5 种不同的公式**，产出 5 条高 CTR 标题。

# 7 种爆款公式
${formulaList}

# 主公调性（必须遵守）
${TONE_KEYWORDS.map(t => `- ${t}`).join('\n')}

# 输出要求
1. 每条标题 ≤ 22 字（小红书标题上限）
2. 至少 3 条带 emoji，从候选中选：${SUGGESTED_EMOJIS.join(' ')}
3. 每条配一句"钩子句"（10-20 字，点题/制造好奇）
4. **严格输出 JSON 数组**，不要任何额外文字：

\`\`\`json
[
  {"title": "...", "formula_id": 1, "formula_name": "数字清单型", "hook": "...", "emoji": "🍃"},
  ...
]
\`\`\`
`;
}

/**
 * 笔记生成 Prompt
 * 策略：5 段式结构，450-550 字控制
 * 段 1：钩子（引发好奇/共鸣，1-2 句）
 * 段 2：场景（具体使用场景，2-3 句）
 * 段 3：干货（核心技巧/方法，3-4 句）
 * 段 4：反差点/反转（出其不意，2-3 句）
 * 段 5：行动召唤（收藏/评论/关注，1-2 句）
 */
function buildNotePrompt(draft) {
  return `你是小红书爆款笔记改写专家。用户输入一段"平淡初稿"，你把它改写成符合小红书调性的爆款体。

# 用户初稿
"""
${draft}
"""

# 主公调性（必须遵守）
${TONE_KEYWORDS.map(t => `- ${t}`).join('\n')}

# 5 段式结构（严格遵守）
1. **钩子段**（1-2 句）：用具体场景/数字/反差引发好奇
2. **场景段**（2-3 句）：交代"什么时候、谁、在哪用"
3. **干货段**（3-4 句）：核心技巧/方法（用数字 + 关键词）
4. **反差点段**（2-3 句）：出其不意/反面案例/避坑提醒
5. **行动召唤段**（1-2 句）：求收藏/求评论/求关注

# 字数控制
- **总字数 450-550 字**（超出扣分，不够扣分）
- 每段之间空一行
- 适当用 emoji（3-5 个），不要堆砌

# 输出要求
**严格输出以下 JSON**，不要任何额外文字：

\`\`\`json
{
  "note": "完整改写后的笔记（保留 \\n 换行）",
  "word_count": 实际字数,
  "tags": ["3-5 个话题标签，每个带 # 前缀"],
  "structure": {
    "hook": "钩子段原文",
    "scene": "场景段原文",
    "value": "干货段原文",
    "twist": "反差点段原文",
    "cta": "行动召唤段原文"
  }
}
\`\`\`
`;
}

export {
  TONE_KEYWORDS,
  TITLE_FORMULAS,
  SUGGESTED_EMOJIS,
  buildTitlePrompt,
  buildNotePrompt,
};
